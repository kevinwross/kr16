from pathlib import Path

root = Path(__file__).resolve().parent
output = root.parent / "src" / "resources" / "embedded_libc.cpp"
header = root.parent / "src" / "resources" / "embedded_libc.hpp"
sources = [
    ("kLibc", "embedded_libc_source", root / "libc.s"),
    ("kFileio", "embedded_fileio_source", root / "fileio.c"),
    (
        "kSystemServices",
        "embedded_systemservices_header",
        root.parent / "include" / "kr16" / "systemservices.h",
    ),
]

header.write_text(
    """#pragma once

#include <cstdint>
#include <span>

namespace kr16 {

std::span<const std::uint8_t> embedded_libc_source();
std::span<const std::uint8_t> embedded_fileio_source();
std::span<const std::uint8_t> embedded_systemservices_header();

}  // namespace kr16
""",
    encoding="utf-8",
)

lines = [
    "// Generated by resources/embed_libc.py; do not edit by hand.",
    '#include "resources/embedded_libc.hpp"',
    "",
    "#include <array>",
    "",
    "namespace kr16 {",
    "namespace {",
]
for array_name, _, source in sources:
    # Normalise line endings before embedding. The embedded copy is compared
    # byte for byte against the checked-in resource, and `.gitattributes` pins
    # those to LF; a checkout made with core.autocrlf=true handed this script
    # CRLF bytes, so the committed array disagreed with the file it came from
    # on every line. The array must not depend on how the tree was checked out.
    data = source.read_bytes().replace(b"\r\n", b"\n")
    lines.append(
        "constexpr std::array<std::uint8_t, "
        + str(len(data))
        + "> "
        + array_name
        + " = {"
    )
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
lines.extend(
    [
        "}  // namespace",
        "",
    ]
)
for array_name, function_name, source in sources:
    lines.extend(
        [
            "std::span<const std::uint8_t> " + function_name + "() {",
            "    return std::span<const std::uint8_t>(" + array_name + ");",
            "}",
            "",
        ]
    )
lines.extend(["}", ""])
# LF in the output as well: the repository pins LF, and text mode on Windows
# would otherwise write CRLF into the working tree and re-normalise on commit.
output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(output)
