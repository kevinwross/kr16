int hex_digit(wchar_t ch) {
    if (ch >= L'0' && ch <= L'9') {
        return ch - L'0';
    }
    if (ch >= L'a' && ch <= L'f') {
        return ch - L'a' + 10;
    }
    if (ch >= L'A' && ch <= L'F') {
        return ch - L'A' + 10;
    }
    return -1;
}

std::string trim_copy(const std::string& text) {
    std::size_t begin = 0;
    while (begin < text.size() &&
           std::isspace(static_cast<unsigned char>(text[begin])) != 0) {
        ++begin;
    }
    std::size_t end = text.size();
    while (end > begin &&
           std::isspace(static_cast<unsigned char>(text[end - 1])) != 0) {
        --end;
    }
    return text.substr(begin, end - begin);
}

bool is_register_operand(const std::string& operand) {
    if (operand == "SP" || operand == "SR" || operand == "PC") {
        return true;
    }
    return operand.size() == 2 && operand[0] == 'R' &&
           operand[1] >= '0' && operand[1] <= '4';
}

bool is_branch_mnemonic(const std::string& mnemonic) {
    if (mnemonic == "JMP" || mnemonic == "CALL") {
        return true;
    }
    static const char* kNames[] = {
        "BEQ", "BNE", "BCS", "BCC", "BMI", "BPL", "BVS", "BVC",
        "BHI", "BLS", "BGE", "BLT", "BGT", "BLE", "BRA", "BNV"};
    for (const char* name : kNames) {
        if (mnemonic == name) {
            return true;
        }
    }
    return false;
}

