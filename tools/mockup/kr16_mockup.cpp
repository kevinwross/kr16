void App::decode_disassembly() {
    instrs_.clear();
    asm_pc_index_ = 0;
    if (!loaded_) {
        return;
    }
    const Func* func = func_at(cpu_.pc());
    std::uint32_t begin = func != nullptr ? func->low : cpu_.pc();
    std::uint32_t end = 0;
    if (func != nullptr) {
        end = func->high;
    } else {
        end = std::min<std::uint32_t>(0x10000, begin + 120);
    }
    if (begin < 0x0100) {
        begin = 0x0100;
    }
    std::uint32_t address = begin;
    while (address + 2 <= end && address + 2 <= 0x10000 &&
           instrs_.size() < 2000) {
        const std::uint16_t pc = static_cast<std::uint16_t>(address);
        const std::uint16_t first = machine_.read16(pc);
        const bool is_long = Instruction::first_word_is_32_bit(first);
        const std::uint16_t size = is_long ? 4 : 2;
        if (address + size > 0x10000) {
            break;
        }
        std::vector<std::uint8_t> bytes;
        bytes.push_back(static_cast<std::uint8_t>(first & 0xFF));
        bytes.push_back(static_cast<std::uint8_t>(first >> 8));
        if (is_long) {
            const std::uint16_t second =
                machine_.read16(static_cast<std::uint16_t>(pc + 2));
            bytes.push_back(static_cast<std::uint8_t>(second & 0xFF));
            bytes.push_back(static_cast<std::uint8_t>(second >> 8));
        }
        std::string text = disassemble_raw(bytes, DisassemblyOptions{pc, false});
        while (!text.empty() && (text.back() == '\n' || text.back() == '\r' ||
                                 text.back() == ' ')) {
            text.pop_back();
        }
        while (!text.empty() && (text.front() == ' ' || text.front() == '\t')) {
            text.erase(0, 1);
        }
        // Strip the leading address that disassemble_raw prints.
        if (text.rfind("0x", 0) == 0) {
            const std::size_t space = text.find(' ');
            if (space != std::string::npos) {
                std::size_t start = space;
                while (start < text.size() && text[start] == ' ') {
                    ++start;
                }
                text = text.substr(start);
            }
        }
        Instr item;
        item.addr = pc;
        item.size = static_cast<std::uint8_t>(size);
        item.text = std::move(text);
        item.bytes = std::move(bytes);
        instrs_.push_back(std::move(item));
        address += size;
    }
    for (std::size_t i = 0; i < instrs_.size(); ++i) {
        if (instrs_[i].addr == cpu_.pc()) {
            asm_pc_index_ = static_cast<int>(i);
            break;
        }
    }
}

void App::toggle_line_breakpoint(int line) {
    if (line <= 0) {
        return;
    }
    int target = line;
    if (exec_lines_.count(target) == 0) {
        target = 0;
        for (int candidate = line + 1;
             candidate <= static_cast<int>(source_lines_.size()); ++candidate) {
            if (exec_lines_.count(candidate) != 0) {
                target = candidate;
                break;
            }
        }
        if (target == 0) {
            message_ = "line has no executable code";
            return;
        }
    }
    if (bp_lines_.count(target) != 0) {
        bp_lines_.erase(target);
        message_ = "breakpoint cleared";
    } else {
        bp_lines_.insert(target);
        message_ = target == line
                       ? "line breakpoint set"
                       : "breakpoint moved to line " + std::to_string(target);
    }
}

void App::toggle_addr_breakpoint(std::uint16_t addr) {
    if (bp_addrs_.count(addr) != 0) {
        bp_addrs_.erase(addr);
        message_ = "address breakpoint cleared";
    } else {
        bp_addrs_.insert(addr);
        message_ = "address breakpoint set";
    }
}

