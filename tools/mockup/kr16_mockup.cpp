// KR16 two-pane debugger mockup.
//
// Throwaway validation prototype, not product code. One Win32/GDI window:
//   - C source pane with its own step-over/in/out buttons
//   - Disassembly pane with its own step-over/in/out buttons
//   - variables, call stack and console strips underneath
//
// It links the existing kr16_core library and executes a real .kr16, so the
// stepping feel can be judged without DAP, VS Code, sockets or threads.
//
// The C stepping model is the one proposed in docs/research/visual-debugger.md:
// one PC, two granularities. Line steps stop when the source line changes,
// with frame depth distinguishing over/in/out.
//
// Two workarounds are applied while loading line information because the
// current compiler/linker still have the defects noted in the research note:
//   1. rows that go backwards inside a .debug_line section are dropped
//      (the linker relocates .crt0 rows by .text's address);
//   2. prologue rows that inherit the previous function's last line are
//      blanked to line 0, so the first C step lands on real code.
// Those belong in the compiler/linker, not in a UI.

