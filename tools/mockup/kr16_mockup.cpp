int App::hit_button(POINT pt) const {
    for (const auto& button : buttons_) {
        if (button.enabled && PtInRect(&button.rect, pt) != FALSE) {
            return button.id;
        }
    }
    return 0;
}

void App::on_mouse_move(POINT pt) {
    mouse_ = pt;
    bool changed = false;
    for (auto& button : buttons_) {
        const bool hover =
            button.enabled && PtInRect(&button.rect, pt) != FALSE;
        if (hover != button.hover) {
            button.hover = hover;
            changed = true;
        }
    }

    int reg = -1;
    int flag = -1;
    if (PtInRect(&reg_area_, pt) != FALSE) {
        for (int i = 0; i < 5; ++i) {
            if (PtInRect(&flag_rects_[i], pt) != FALSE) {
                flag = i;
                break;
            }
        }
        if (flag < 0) {
            for (int i = 0; i < 8; ++i) {
                if (PtInRect(&reg_rects_[i], pt) != FALSE) {
                    reg = i;
                    break;
                }
            }
        }
    }
    if (reg != hover_reg_ || flag != hover_flag_) {
        hover_reg_ = reg;
        hover_flag_ = flag;
        changed = true;
    }
    if (hover_reg_ >= 0 || hover_flag_ >= 0) {
        // Let the tooltip follow the cursor inside the same cell.
        changed = true;
    }

    int var = -1;
    if (PtInRect(&layout_.variables, pt) != FALSE) {
        for (int i = 0; i < static_cast<int>(var_hits_.size()); ++i) {
            if (PtInRect(&var_hits_[i].rect, pt) != FALSE) {
                var = i;
                break;
            }
        }
    }
    if (var != hover_var_) {
        hover_var_ = var;
        changed = true;
    }
    if (hover_var_ >= 0) {
        changed = true;
    }

    const bool memory_up =
        PtInRect(&layout_.memory_up, pt) != FALSE;
    const bool memory_down =
        PtInRect(&layout_.memory_down, pt) != FALSE;
    if (memory_up != hover_mem_up_ || memory_down != hover_mem_down_) {
        hover_mem_up_ = memory_up;
        hover_mem_down_ = memory_down;
        changed = true;
    }

    int mem_byte = -1;
    std::uint16_t mem_byte_address = 0;
    for (int i = 0; i < 32; ++i) {
        if (mem_byte_rects_[i].right <= mem_byte_rects_[i].left) {
            continue;
        }
        if (PtInRect(&mem_byte_rects_[i], pt) != FALSE) {
            mem_byte = i;
            mem_byte_address = static_cast<std::uint16_t>(
                mem_address_ + static_cast<std::uint16_t>(i));
            break;
        }
    }
    if (mem_byte != hover_mem_byte_) {
        hover_mem_byte_ = mem_byte;
        hover_mem_byte_address_ = mem_byte_address;
        changed = true;
    }
    if (hover_mem_byte_ >= 0) {
        changed = true;
    }

    AsmHoverKind asm_kind = AsmHoverKind::None;
    int asm_index = -1;
    if (PtInRect(&layout_.aText, pt) != FALSE) {
        const int row =
            asm_scroll_ + static_cast<int>(pt.y - layout_.aText.top) /
                              std::max(1, line_h_);
        if (row >= 0 && row < static_cast<int>(instrs_.size()) &&
            row < static_cast<int>(asm_mnemonic_rects_.size())) {
            if (PtInRect(&asm_mnemonic_rects_[row], pt) != FALSE) {
                asm_kind = AsmHoverKind::Mnemonic;
                asm_index = row;
            } else if (row < static_cast<int>(asm_operand_rects_.size()) &&
                       PtInRect(&asm_operand_rects_[row], pt) != FALSE) {
                asm_kind = AsmHoverKind::Operand;
                asm_index = row;
            }
        }
    }
    if (asm_kind != hover_asm_kind_ || asm_index != hover_asm_index_) {
        hover_asm_kind_ = asm_kind;
        hover_asm_index_ = asm_index;
        changed = true;
    }
    if (hover_asm_kind_ != AsmHoverKind::None) {
        changed = true;
    }

    if (changed) {
        InvalidateRect(g_hwnd, nullptr, FALSE);
    }
    if (!tracking_mouse_) {
        TRACKMOUSEEVENT track{};
        track.cbSize = sizeof(track);
        track.dwFlags = TME_LEAVE;
        track.hwndTrack = g_hwnd;
        TrackMouseEvent(&track);
        tracking_mouse_ = true;
    }
}

void App::on_mouse_leave() {
    tracking_mouse_ = false;
    bool changed = false;
    for (auto& button : buttons_) {
        if (button.hover) {
            button.hover = false;
            changed = true;
        }
    }
    if (hover_reg_ >= 0 || hover_flag_ >= 0) {
        hover_reg_ = -1;
        hover_flag_ = -1;
        changed = true;
    }
    if (hover_var_ >= 0) {
        hover_var_ = -1;
        changed = true;
    }
    if (hover_mem_up_ || hover_mem_down_) {
        hover_mem_up_ = false;
        hover_mem_down_ = false;
        changed = true;
    }
    if (hover_mem_byte_ >= 0) {
        hover_mem_byte_ = -1;
        changed = true;
    }
    if (hover_asm_kind_ != AsmHoverKind::None || hover_asm_index_ >= 0) {
        hover_asm_kind_ = AsmHoverKind::None;
        hover_asm_index_ = -1;
        changed = true;
    }
    if (changed) {
        InvalidateRect(g_hwnd, nullptr, FALSE);
    }
}

void App::on_click(POINT pt) {
    if (editing()) {
        RECT active{};
        bool has_active = false;
        if (editing_mem_byte_ >= 0 &&
            mem_byte_rects_[editing_mem_byte_].right >
                mem_byte_rects_[editing_mem_byte_].left) {
            active = mem_byte_rects_[editing_mem_byte_];
            has_active = true;
        } else if (editing_mem_) {
            active = layout_.memory_address;
            has_active = true;
        } else if (editing_reg_ >= 0) {
            active = reg_rects_[editing_reg_];
            has_active = true;
        } else if (editing_var_ >= 0 &&
                   editing_var_ < static_cast<int>(var_hits_.size())) {
            active = var_hits_[editing_var_].rect;
            has_active = true;
        }
        if (has_active && PtInRect(&active, pt) != FALSE) {
            return;
        }
        finish_edit(true);
        if (editing()) {
            return;
        }
    }

    const int id = hit_button(pt);
    switch (id) {
        case BtnLoad:
            open_file();
            return;
        case BtnRun:
            start_run();
            return;
        case BtnBreak:
            stop_run("paused by Break");
            return;
        case BtnRestart: {
            stop_run("stopped");
            std::string error;
            if (!load(image_path_, error)) {
                message_ = "restart failed: " + error;
            }
            after_action();
            return;
        }
        case BtnReload: {
            stop_run("stopped");
            bp_addrs_.clear();
            bp_lines_.clear();
            std::string error;
            if (!load(image_path_, error)) {
                message_ = "reload failed: " + error;
            }
            after_action();
            return;
        }
        case BtnResetStats:
            reset_stats();
            return;
        case BtnCOver:
            step_line(LineMode::Over);
            after_action();
            return;
        case BtnCIn:
            step_line(LineMode::In);
            after_action();
            return;
        case BtnCOut:
            step_line(LineMode::Out);
            after_action();
            return;
        case BtnAOver:
            step_instruction_over();
            after_action();
            return;
        case BtnAIn:
            step_instruction_in();
            after_action();
            return;
        case BtnAOut:
            step_instruction_out();
            after_action();
            return;
        default:
            break;
    }

    if (PtInRect(&reg_area_, pt) != FALSE) {
        for (int i = 0; i < 5; ++i) {
            if (PtInRect(&flag_rects_[i], pt) != FALSE) {
                toggle_flag(i);
                return;
            }
        }
        for (int i = 0; i < 8; ++i) {
            if (PtInRect(&reg_rects_[i], pt) != FALSE) {
                start_edit(i);
                return;
            }
        }
        return;
    }

    if (PtInRect(&layout_.memory, pt) != FALSE) {
        if (PtInRect(&layout_.memory_address, pt) != FALSE) {
            start_mem_edit();
            return;
        }
        if (PtInRect(&layout_.memory_up, pt) != FALSE) {
            scroll_memory(-16);
            return;
        }
        if (PtInRect(&layout_.memory_down, pt) != FALSE) {
            scroll_memory(16);
            return;
        }
        for (int i = 0; i < 32; ++i) {
            if (mem_byte_rects_[i].right <= mem_byte_rects_[i].left) {
                continue;
            }
            if (PtInRect(&mem_byte_rects_[i], pt) != FALSE) {
                start_mem_byte_edit(i);
                return;
            }
        }
        return;
    }

    if (PtInRect(&layout_.variables, pt) != FALSE) {
        for (int i = 0; i < static_cast<int>(var_hits_.size()); ++i) {
            if (PtInRect(&var_hits_[i].rect, pt) != FALSE) {
                start_variable_edit(i);
                return;
            }
        }
        return;
    }

    if (PtInRect(&layout_.cText, pt) != FALSE &&
        pt.x < layout_.cText.left + kGutter) {
        const int index =
            c_scroll_ +
            static_cast<int>(pt.y - layout_.cText.top) / std::max(1, line_h_);
        if (index >= 0 && index < static_cast<int>(source_lines_.size())) {
            toggle_line_breakpoint(index + 1);
            after_action();
        }
        return;
    }
    if (PtInRect(&layout_.aText, pt) != FALSE &&
        pt.x < layout_.aText.left + kAsmGutter) {
        const int index =
            asm_scroll_ +
            static_cast<int>(pt.y - layout_.aText.top) / std::max(1, line_h_);
        if (index >= 0 && index < static_cast<int>(instrs_.size())) {
            toggle_addr_breakpoint(instrs_[index].addr);
            after_action();
        }
        return;
    }
}

void App::on_wheel(POINT pt, int delta) {
    if (PtInRect(&layout_.memory, pt) != FALSE) {
        scroll_memory(delta > 0 ? -16 : 16);
        return;
    }
    const int steps = -delta / WHEEL_DELTA * 3;
    if (PtInRect(&layout_.cText, pt) != FALSE) {
        c_scroll_ += steps;
    } else if (PtInRect(&layout_.aText, pt) != FALSE) {
        asm_scroll_ += steps;
        hover_asm_kind_ = AsmHoverKind::None;
        hover_asm_index_ = -1;
    } else {
        return;
    }
    clamp_scrolls();
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

void App::on_key(WPARAM key) {
    if (running_) {
        if (key == VK_F6) {
            stop_run("paused by Break");
        }
        return;
    }
    const bool control = (GetKeyState(VK_CONTROL) & 0x8000) != 0;
    const bool shift = (GetKeyState(VK_SHIFT) & 0x8000) != 0;
    if (key == VK_F5) {
        start_run();
    } else if (key == VK_F6) {
        stop_run("paused by Break");
    } else if (key == VK_F10 && control) {
        step_instruction_over();
    } else if (key == VK_F11 && control && shift) {
        step_instruction_out();
    } else if (key == VK_F11 && control) {
        step_instruction_in();
    } else if (key == VK_F11 && shift) {
        step_line(LineMode::Out);
    } else if (key == VK_F10) {
        step_line(LineMode::Over);
    } else if (key == VK_F11) {
        step_line(LineMode::In);
    } else {
        return;
    }
    after_action();
}

