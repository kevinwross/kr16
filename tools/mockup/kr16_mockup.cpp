void App::load_any(const std::filesystem::path& path) {
    stop_run("stopped");

    std::wstring extension = path.extension().wstring();
    for (auto& character : extension) {
        character = static_cast<wchar_t>(std::towlower(character));
    }
    const bool is_image = extension == L".kr16";
    const bool is_source = extension == L".c" || extension == L".s" ||
                           extension == L".asm" || extension == L".o";
    if (!is_image && !is_source) {
        show_error(L"Unsupported file",
                   "Choose a .kr16, .c, .s, .asm, or .o file.");
        return;
    }

    std::filesystem::path image = path;
    if (!is_image) {
        prepare_embedded_libc();
        BuildOptions options;
        options.input = path;
        options.output =
            path.parent_path() / (path.stem().wstring() + L".kr16");
        options.debug = true;
        // C input always links libc. Set it explicitly for every built source
        // so a loaded C file can call printf/puts without extra flags.
        options.link_libc = true;
        options.command = "load";
        std::ostringstream diagnostics;
        HCURSOR previous = SetCursor(LoadCursorW(nullptr, IDC_WAIT));
        const BuildResult result = build_program(options, diagnostics);
        SetCursor(previous);
        if (!result.ok) {
            std::string message = diagnostics.str();
            if (message.empty()) {
                message = "build failed";
            }
            show_error(L"KR16 build failed", message);
            return;
        }
        image = result.executable.empty() ? options.output : result.executable;
    }

    bp_lines_.clear();
    bp_addrs_.clear();
    std::string error;
    if (!load(image, error)) {
        show_error(L"KR16 load failed", error);
        return;
    }
    update_title();
    after_action();
}

void App::load_path(const std::filesystem::path& path) {
    load_any(path);
}

