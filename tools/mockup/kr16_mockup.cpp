std::vector<std::string> split_pipe(const std::string& text) {
    std::vector<std::string> parts;
    std::size_t begin = 0;
    for (;;) {
        const std::size_t end = text.find('|', begin);
        if (end == std::string::npos) {
            parts.push_back(text.substr(begin));
            break;
        }
        parts.push_back(text.substr(begin, end - begin));
        begin = end + 1;
    }
    return parts;
}

std::vector<std::string> split_records(const Section& section) {
    std::vector<std::string> records;
    std::string current;
    for (const std::uint8_t byte : section.data) {
        if (byte == 0) {
            if (!current.empty()) {
                records.push_back(current);
                current.clear();
            }
        } else {
            current.push_back(static_cast<char>(byte));
        }
    }
    if (!current.empty()) {
        records.push_back(current);
    }
    return records;
}

// The compiler writes raw Windows paths into .file / .debug_sources and the
// assembler's string unquoting turns \r, \n and \t into control characters.
// Put the backslash back so the mock can open the file. The product fix is to
// emit escaped or forward-slash paths.
std::string repair_debug_path(const std::string& input) {
    std::string result;
    for (const char ch : input) {
        switch (ch) {
            case '\r': result += "\\r"; break;
            case '\n': result += "\\n"; break;
            case '\t': result += "\\t"; break;
            default: result.push_back(ch); break;
        }
    }
    return result;
}

std::vector<std::string> split_lines(const std::string& text) {    std::vector<std::string> lines;
    std::string current;
    for (const char ch : text) {
        if (ch == '\n') {
            if (!current.empty() && current.back() == '\r') {
                current.pop_back();
            }
            lines.push_back(current);
            current.clear();
        } else {
            current.push_back(ch);
        }
    }
    if (!current.empty()) {
        lines.push_back(current);
    }
    return lines;
}

std::wstring hex4(std::uint16_t value) {
    return wformat(L"0x%04X", static_cast<unsigned>(value));
}

std::wstring decimal_with_commas(std::uint64_t value) {
    const std::wstring digits = std::to_wstring(value);
    std::wstring result;
    int count = 0;
    for (auto it = digits.rbegin(); it != digits.rend(); ++it) {
        if (count != 0 && count % 3 == 0) {
            result.push_back(L',');
        }
        result.push_back(*it);
        ++count;
    }
    std::reverse(result.begin(), result.end());
    return result;
}

std::wstring format_duration(std::uint64_t milliseconds) {
    const std::uint64_t total_seconds = milliseconds / 1000;
    const std::uint64_t hours = total_seconds / 3600;
    const std::uint64_t minutes = (total_seconds % 3600) / 60;
    const std::uint64_t seconds = total_seconds % 60;
    const std::uint64_t millis = milliseconds % 1000;
    return wformat(L"%02llu:%02llu:%02llu:%03llu",
                   static_cast<unsigned long long>(hours),
                   static_cast<unsigned long long>(minutes),
                   static_cast<unsigned long long>(seconds),
                   static_cast<unsigned long long>(millis));
}

std::wstring format_rate(double rate) {
    if (rate >= 1.0e9) {
        return wformat(L"%.2fG", rate / 1.0e9);
    }
    if (rate >= 1.0e6) {
        return wformat(L"%.2fM", rate / 1.0e6);
    }
    if (rate >= 1.0e3) {
        return wformat(L"%.1fK", rate / 1.0e3);
    }
    return wformat(L"%.0f", rate);
}

