std::wstring describe_operand(const std::string& raw,
                              const std::string& mnemonic) {
    const std::string operand = trim_copy(raw);
    if (operand.empty()) {
        return L"";
    }
    if (operand.front() == '#') {
        return mnemonic == "SYS"
                   ? L"immediate host-service number"
                   : L"immediate value (encoded in the instruction)";
    }
    if (operand.front() == '[' && operand.back() == ']') {
        const std::string inner =
            trim_copy(operand.substr(1, operand.size() - 2));
        if (is_register_operand(inner)) {
            return L"register indirect (the register holds the address)";
        }
        const std::size_t sign = inner.find_first_of("+-");
        if (sign != std::string::npos &&
            is_register_operand(trim_copy(inner.substr(0, sign)))) {
            return L"register indirect with displacement "
                   L"(address = register +/- displacement)";
        }
        return L"absolute memory address (constant address)";
    }
    if (is_register_operand(operand)) {
        if (operand == "SP" || operand == "SR" || operand == "PC") {
            return L"special register (direct)";
        }
        if (mnemonic == "JMP" || mnemonic == "CALL") {
            return L"register target (PC is loaded from the register)";
        }
        return L"register direct (the register itself)";
    }
    if (operand.rfind("0x", 0) == 0 ||
        (operand.front() >= '0' && operand.front() <= '9')) {
        return is_branch_mnemonic(mnemonic)
                   ? L"PC-relative target (offset from the next instruction)"
                   : L"absolute value";
    }
    return L"other operand";
}

std::wstring addressing_help(const std::string& instruction,
                             const std::string& mnemonic) {
    const std::size_t space = instruction.find(' ');
    if (space == std::string::npos) {
        return L"This instruction has no operands.";
    }
    const std::string operands = instruction.substr(space + 1);
    std::wstring result;
    bool first = true;
    std::size_t begin = 0;
    while (begin <= operands.size()) {
        const std::size_t comma = operands.find(',', begin);
        const std::string piece = trim_copy(operands.substr(
            begin, comma == std::string::npos ? std::string::npos
                                              : comma - begin));
        if (!piece.empty()) {
            if (!first) {
                result += L"; ";
            }
            result += widen(piece) + L": " + describe_operand(piece, mnemonic);
            first = false;
        }
        if (comma == std::string::npos) {
            break;
        }
        begin = comma + 1;
    }
    if (first) {
        return L"This instruction has no operands.";
    }
    return result;
}

