void App::start_variable_edit(int index) {
    if (!loaded_ || running_ || index < 0 ||
        index >= static_cast<int>(var_hits_.size())) {
        return;
    }
    const VarHit& hit = var_hits_[index];
    if (!hit.ok) {
        message_ = "value is unavailable at this PC";
        InvalidateRect(g_hwnd, nullptr, FALSE);
        return;
    }
    if (hit.size > 2) {
        message_ = "aggregate variables are not editable";
        InvalidateRect(g_hwnd, nullptr, FALSE);
        return;
    }
    editing_var_ = index;
    editing_reg_ = -1;
    const unsigned current = hit.size == 1 ? machine_.read8(hit.address)
                                           : machine_.read16(hit.address);
    edit_text_ = wformat(hit.size == 1 ? L"%02X" : L"%04X", current);
    edit_fresh_ = true;
    message_ = "editing " + hit.name;
    SetFocus(g_hwnd);
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

