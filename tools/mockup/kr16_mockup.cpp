const Func* App::func_at(std::uint16_t pc) const {
    for (const auto& func : funcs_) {
        if (pc >= func.low && pc < func.high) {
            return &func;
        }
    }
    return nullptr;
}

std::string App::func_name_at(std::uint16_t pc) const {
    if (const Func* func = func_at(pc); func != nullptr) {
        return func->name;
    }
    for (const auto& symbol : container_.symbols) {
        if (symbol.value == pc && !symbol.name.empty()) {
            return symbol.name;
        }
    }
    return "<program>";
}

int App::line_at(std::uint16_t pc) const {
    const Func* func = func_at(pc);
    if (func == nullptr || func->rows.empty()) {
        return 0;
    }
    if (pc < func->rows.front().addr) {
        return 0;
    }
    const auto it = std::upper_bound(
        func->rows.begin(), func->rows.end(), pc,
        [](std::uint16_t value, const Row& row) { return value < row.addr; });
    if (it == func->rows.begin()) {
        return 0;
    }
    return (it - 1)->line;
}

std::uint16_t App::register_value(int index) const {
    switch (index) {
        case 0:
        case 1:
        case 2:
        case 3:
        case 4:
            return cpu_.reg(static_cast<std::uint8_t>(index));
        case 5:
            return cpu_.pc();
        case 6:
            return cpu_.sp();
        case 7:
            return cpu_.sr();
        default:
            return 0;
    }
}

int App::frame_depth() {
    int depth = 0;
    std::uint16_t fp = cpu_.reg(4);
    for (int i = 0; i < 32; ++i) {
        if (fp < 0x0100 || fp >= 0xF000) {
            break;
        }
        ++depth;
        const std::uint16_t saved = machine_.read16(fp);
        if (saved == 0) {
            break;
        }
        fp = saved;
    }
    return depth;
}

std::vector<Frame> App::frames() {
    std::vector<Frame> result;
    std::uint16_t pc = cpu_.pc();
    std::uint16_t fp = cpu_.reg(4);
    for (int i = 0; i < 32; ++i) {
        Frame item;
        item.pc = pc;
        item.name = func_name_at(pc);
        item.line = line_at(pc);
        result.push_back(item);
        if (fp < 0x0100 || fp >= 0xF000) {
            break;
        }
        const std::uint16_t saved = machine_.read16(fp);
        const std::uint16_t ret = machine_.read16(static_cast<std::uint16_t>(fp + 2));
        if (saved == 0 || ret < 0x0100) {
            break;
        }
        pc = ret;
        fp = saved;
    }
    return result;
}

std::vector<LocalValue> App::locals_now() {
    std::vector<LocalValue> result;
    const Func* func = func_at(cpu_.pc());
    if (func == nullptr) {
        return result;
    }
    const std::uint16_t fp = cpu_.reg(4);
    for (const auto& var : vars_) {
        if (var.func != func->name) {
            continue;
        }
        LocalValue item;
        item.name = var.name;
        item.size = var.size > 0 ? var.size : 2;
        const std::uint16_t address =
            static_cast<std::uint16_t>(fp - static_cast<std::uint16_t>(var.offset));
        item.address = address;
        item.ok = fp >= 0x0100 && fp < 0xF000 && address >= 0x0100 &&
                  static_cast<std::uint32_t>(address) +
                          static_cast<std::uint32_t>(item.size) <=
                      0xF000;
        if (item.ok) {
            item.value = item.size == 1 ? machine_.read8(address)
                                        : machine_.read16(address);
        }
        result.push_back(item);
    }
    return result;
}

std::vector<GlobalValue> App::globals_now() {
    std::vector<GlobalValue> result;
    for (const auto& symbol : container_.symbols) {
        if (symbol.section == 0 || symbol.section > container_.sections.size()) {
            continue;
        }
        const auto& section = container_.sections[symbol.section - 1];
        if (section.name != ".data" && section.name != ".bss") {
            continue;
        }
        if (symbol.value >= 0xF000) {
            continue;
        }
        GlobalValue item;
        item.name = symbol.name;
        item.address = symbol.value;
        item.size = symbol.size > 0 ? static_cast<int>(symbol.size) : 2;
        item.ok = static_cast<std::uint32_t>(symbol.value) +
                      static_cast<std::uint32_t>(item.size) <=
                  0xF000;
        if (item.ok) {
            item.value = item.size == 1 ? machine_.read8(symbol.value)
                                        : machine_.read16(symbol.value);
        }
        result.push_back(item);
        if (result.size() >= 12) {
            break;
        }
    }
    return result;
}

void App::drain_console() {
    const auto& output = machine_.console_output();
    if (output.empty()) {
        return;
    }
    console_.append(reinterpret_cast<const char*>(output.data()), output.size());
    if (console_.size() > 32768) {
        console_.erase(0, console_.size() - 32768);
    }
    machine_.clear_console_output();
}

bool App::step_one() {
    if (!loaded_ || cpu_.halted()) {
        return false;
    }
    const std::uint32_t used = cpu_.step(machine_);
    if (used == 0) {
        message_ = "halted";
        return false;
    }
    machine_.tick(used);
    ++instructions_;
    drain_console();
    if (cpu_.halted()) {
        message_ = "halted";
        return false;
    }
    return true;
}

bool App::step_line(LineMode mode) {
    if (!loaded_ || cpu_.halted()) {
        return false;
    }
    const int start_depth = frame_depth();
    int previous = line_at(cpu_.pc());

    // Before the first C line (typically inside _start) every C step means
    // "get me to C code": run until line information appears.
    if (previous == 0) {
        for (std::uint64_t i = 0; i < 5'000'000; ++i) {
            if (!step_one()) {
                return false;
            }
            if (line_at(cpu_.pc()) != 0) {
                message_ = "entered C";
                return true;
            }
        }
        message_ = "no C source found";
        return false;
    }

    for (std::uint64_t i = 0; i < 5'000'000; ++i) {
        if (!step_one()) {
            return false;
        }
        const int current = line_at(cpu_.pc());
        if (current != 0 && current != previous) {
            const int depth = frame_depth();
            bool stop = false;
            if (mode == LineMode::In) {
                stop = true;
            } else if (mode == LineMode::Over) {
                stop = depth <= start_depth;
            } else {
                stop = depth < start_depth;
            }
            if (stop) {
                message_ = "line step";
                return true;
            }
        }
        if (current != 0) {
            previous = current;
        }
    }
    message_ = "line step budget";
    return false;
}

void App::run_until_pc(std::uint16_t target) {
    for (std::uint64_t i = 0; i < 20'000'000; ++i) {
        if (!step_one()) {
            return;
        }
        if (cpu_.pc() == target) {
            return;
        }
    }
    message_ = "instruction budget";
}

void App::step_instruction_in() {
    if (!loaded_ || cpu_.halted()) {
        return;
    }
    if (step_one()) {
        message_ = "instruction";
    }
}

void App::step_instruction_over() {
    if (!loaded_ || cpu_.halted()) {
        return;
    }
    const std::uint16_t pc = cpu_.pc();
    const std::uint16_t first = machine_.read16(pc);
    const bool is_long = Instruction::first_word_is_32_bit(first);
    const std::uint16_t second =
        is_long ? machine_.read16(static_cast<std::uint16_t>(pc + 2)) : 0;
    const Instruction instruction = Instruction::decode(first, second);
    const std::uint16_t next =
        static_cast<std::uint16_t>(pc + (is_long ? 4 : 2));
    if (instruction.op == Op::CallRel || instruction.op == Op::CallReg) {
        run_until_pc(next);
        message_ = "instruction over";
    } else if (step_one()) {
        message_ = "instruction";
    }
}

void App::step_instruction_out() {
    if (!loaded_ || cpu_.halted()) {
        return;
    }
    const std::uint16_t fp = cpu_.reg(4);
    if (fp >= 0x0100 && fp <= 0xFFFC) {
        const std::uint16_t target =
            machine_.read16(static_cast<std::uint16_t>(fp + 2));
        if (target >= 0x0100) {
            run_until_pc(target);
            message_ = "instruction out";
            return;
        }
    }
    if (step_one()) {
        message_ = "instruction";
    }
}

void App::start_run() {
    if (!loaded_ || cpu_.halted() || running_) {
        return;
    }
    running_ = true;
    run_started_ms_ = GetTickCount64();
    run_previous_line_ = line_at(cpu_.pc());
    message_ = "running";
    SetTimer(g_hwnd, kRunTimer, 8, nullptr);
    layout_buttons();
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

void App::stop_run(const std::string& reason) {
    if (!running_) {
        return;
    }
    accumulated_run_ms_ += GetTickCount64() - run_started_ms_;
    run_started_ms_ = 0;
    running_ = false;
    KillTimer(g_hwnd, kRunTimer);
    message_ = reason;
    after_action();
}

std::uint64_t App::elapsed_run_ms() const {
    if (!running_) {
        return accumulated_run_ms_;
    }
    return accumulated_run_ms_ + (GetTickCount64() - run_started_ms_);
}

void App::reset_stats() {
    instructions_ = 0;
    accumulated_run_ms_ = 0;
    run_started_ms_ = running_ ? GetTickCount64() : 0;
    message_ = "stats reset";
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

void App::on_run_slice() {
    if (!running_) {
        return;
    }
    const ULONGLONG started = GetTickCount64();
    for (int i = 0; i < 200000; ++i) {
        if (!step_one()) {
            stop_run("halted");
            return;
        }
        const int current = line_at(cpu_.pc());
        if (current != 0 && current != run_previous_line_ &&
            bp_lines_.count(current) != 0) {
            stop_run("line breakpoint");
            return;
        }
        if (bp_addrs_.count(cpu_.pc()) != 0) {
            stop_run("address breakpoint");
            return;
        }
        if (current != 0) {
            run_previous_line_ = current;
        }
        if ((i & 0x3FF) == 0 && GetTickCount64() - started >= 6) {
            break;
        }
    }
    refresh();
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

