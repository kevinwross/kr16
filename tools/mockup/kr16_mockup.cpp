void App::draw_source_text(HDC dc) {
    const RECT area = layout_.cText;
    fill(dc, area, kPanel);
    RECT gutter = RECT{area.left, area.top, area.left + kGutter, area.bottom};
    fill(dc, gutter, kPanelAlt);
    RECT gutter_line = RECT{area.left + kGutter, area.top,
                            area.left + kGutter + 1, area.bottom};
    fill(dc, gutter_line, kBorder);

    const int saved = SaveDC(dc);
    IntersectClipRect(dc, area.left, area.top, area.right, area.bottom);
    SelectObject(dc, mono_font_);

    if (source_lines_.empty()) {
        const std::wstring message =
            loaded_ ? L"(source file not found: " + widen(source_path_) + L")"
                    : L"(no program loaded)";
        text_left(dc, area.left + 16, area.top + 16, message, kTextDim);
        RestoreDC(dc, saved);
        return;
    }

    const int current = line_at(cpu_.pc());
    const int visible = visible_rows(area);
    for (int i = 0; i < visible; ++i) {
        const int index = c_scroll_ + i;
        if (index >= static_cast<int>(source_lines_.size())) {
            break;
        }
        const int y = area.top + i * line_h_;
        const int line = index + 1;
        if (line == current) {
            fill(dc, RECT{area.left, y, area.right, y + line_h_}, kHighlight);
            fill(dc, RECT{area.left, y, area.left + 3, y + line_h_}, kAccent);
        }
        if (bp_lines_.count(line) != 0) {
            HBRUSH brush = CreateSolidBrush(kRed);
            const HGDIOBJ old_brush = SelectObject(dc, brush);
            const HGDIOBJ old_pen = SelectObject(dc, GetStockObject(NULL_PEN));
            Ellipse(dc, area.left + 12, y + 5, area.left + 20, y + 13);
            SelectObject(dc, old_pen);
            SelectObject(dc, old_brush);
            DeleteObject(brush);
        }
        text_right(dc, area.left + kGutter - 8, y, std::to_wstring(line),
                   kTextDim);
        COLORREF color = exec_lines_.count(line) != 0 ? kText : kTextDim;
        if (line == current) {
            color = RGB(255, 255, 255);
        }
        text_left(dc, area.left + kGutter + 8, y,
                  widen(source_lines_[index]), color);
    }
    RestoreDC(dc, saved);
}

void App::draw_memory(HDC dc) {
    const RECT area = layout_.memory;
    fill(dc, area, kPanelAlt);
    const RECT separator = RECT{area.left, area.top, area.right,
                                area.top + 1};
    fill(dc, separator, kBorder);

    SelectObject(dc, bold_font_);
    text_left(dc, area.left + 10, area.top + 3, L"Memory", kAccent);
    SelectObject(dc, ui_font_);
    text_right(dc, layout_.memory_address.left - 8, area.top + 4, L"ADDR",
               kTextDim);

    fill(dc, layout_.memory_address,
         editing_mem_ ? kHighlight : kPanel);
    frame_rect(dc, layout_.memory_address,
               editing_mem_ ? kAccent : kBorder);
    SelectObject(dc, memory_font_);
    if (editing_mem_) {
        SIZE digits{};
        GetTextExtentPoint32W(dc, L"0000", 4, &digits);
        const int digit_width = static_cast<int>(digits.cx) / 4;
        const int prefix_x = layout_.memory_address.left + 5;
        text_left(dc, prefix_x, area.top + 4, L"0x", kTextDim);
        const int buffer_x = prefix_x + 17;
        if (edit_fresh_) {
            const RECT selection =
                RECT{buffer_x - 1, area.top + 3,
                     buffer_x + 4 * digit_width + 1, area.top + 21};
            fill(dc, selection, kAccentDim);
        }
        text_left(dc, buffer_x, area.top + 4, edit_text_, kText);
        const int caret_x =
            buffer_x + static_cast<int>(edit_text_.size()) * digit_width;
        fill(dc, RECT{caret_x, area.top + 5, caret_x + 1, area.top + 19},
             kAccent);
    } else {
        text_left(dc, layout_.memory_address.left + 5, area.top + 4,
                  wformat(L"0x%04X", mem_address_), kText);
    }

    const RECT arrows[2] = {layout_.memory_up, layout_.memory_down};
    const wchar_t* arrow_text[2] = {L"\x25B2", L"\x25BC"};
    const bool arrow_hover[2] = {hover_mem_up_, hover_mem_down_};
    SelectObject(dc, ui_font_);
    for (int i = 0; i < 2; ++i) {
        fill(dc, arrows[i], arrow_hover[i] ? kButtonHover : kButton);
        frame_rect(dc, arrows[i], kBorder);
        RECT label = arrows[i];
        SetBkMode(dc, TRANSPARENT);
        SetTextColor(dc, kText);
        DrawTextW(dc, arrow_text[i], -1, &label,
                  DT_CENTER | DT_VCENTER | DT_SINGLELINE | DT_NOPREFIX);
    }

    SelectObject(dc, memory_font_);
    SIZE digit_size{};
    GetTextExtentPoint32W(dc, L"0", 1, &digit_size);
    const int char_width = std::max(4, static_cast<int>(digit_size.cx));
    const int line_height = 18;
    const int base_x = area.left + 10;
    const int byte_x = base_x + 8 * char_width;
    for (auto& rect : mem_byte_rects_) {
        rect = RECT{};
    }

    for (int line = 0; line < 2; ++line) {
        const std::uint16_t base = static_cast<std::uint16_t>(
            mem_address_ + static_cast<std::uint16_t>(line * 16));
        const int y = area.top + 26 + line * line_height;
        text_left(dc, base_x, y, wformat(L"0x%04X:", base), kText);

        for (int i = 0; i < 16; ++i) {
            const std::uint16_t address =
                static_cast<std::uint16_t>(base + static_cast<std::uint16_t>(i));
            const std::uint8_t value = machine_.read8(address);
            const int index = line * 16 + i;
            const int x = byte_x + i * 3 * char_width;
            const RECT cell = RECT{x, y, x + 2 * char_width, y + line_height};
            mem_byte_rects_[index] = cell;
            const bool is_editing = editing_mem_byte_ == index;
            const bool hovered = hover_mem_byte_ == index;
            if (is_editing) {
                fill(dc, cell, kHighlight);
                frame_rect(dc, cell, kAccent);
            } else if (hovered) {
                fill(dc, cell, kStmt);
                frame_rect(dc, cell, kAccent);
            }
            if (is_editing) {
                if (edit_fresh_) {
                    RECT selection = cell;
                    selection.left -= 1;
                    selection.right += 1;
                    selection.top += 2;
                    selection.bottom -= 2;
                    fill(dc, selection, kAccentDim);
                }
                text_left(dc, x, y, edit_text_, kText);
                const int caret_x =
                    x + static_cast<int>(edit_text_.size()) * char_width;
                fill(dc, RECT{caret_x, y + 3, caret_x + 1,
                              y + line_height - 3},
                     kAccent);
            } else {
                text_left(dc, x, y,
                          wformat(L"%02X", static_cast<unsigned>(value)),
                          kText);
            }
        }

        std::wstring ascii;
        for (int i = 0; i < 16; ++i) {
            const std::uint8_t value = machine_.read8(
                static_cast<std::uint16_t>(base + static_cast<std::uint16_t>(i)));
            ascii.push_back(value >= 32 && value < 127
                                ? static_cast<wchar_t>(value)
                                : L'.');
        }
        text_left(dc, byte_x + 16 * 3 * char_width + 2 * char_width, y,
                  ascii, kTextDim);
    }
}

void App::draw_asm_text(HDC dc) {
    const RECT area = layout_.aText;
    fill(dc, area, kPanel);
    RECT gutter = RECT{area.left, area.top, area.left + kAsmGutter,
                       area.bottom};
    fill(dc, gutter, kPanelAlt);
    RECT gutter_line = RECT{area.left + kAsmGutter, area.top,
                            area.left + kAsmGutter + 1, area.bottom};
    fill(dc, gutter_line, kBorder);

    const int saved = SaveDC(dc);
    IntersectClipRect(dc, area.left, area.top, area.right, area.bottom);
    SelectObject(dc, mono_font_);

    if (instrs_.empty()) {
        text_left(dc, area.left + 16, area.top + 16,
                  L"(no code disassembled)", kTextDim);
        RestoreDC(dc, saved);
        return;
    }

    const std::uint16_t pc = cpu_.pc();
    const int current_line = line_at(pc);
    const int visible = visible_rows(area);
    asm_mnemonic_rects_.assign(instrs_.size(), RECT{});
    asm_operand_rects_.assign(instrs_.size(), RECT{});
    for (int i = 0; i < visible; ++i) {
        const int index = asm_scroll_ + i;
        if (index >= static_cast<int>(instrs_.size())) {
            break;
        }
        const Instr& instruction = instrs_[index];
        const int y = area.top + i * line_h_;
        const int instruction_line = line_at(instruction.addr);
        const bool is_pc = instruction.addr == pc;
        const bool in_statement =
            current_line != 0 && instruction_line == current_line;
        if (is_pc) {
            fill(dc, RECT{area.left, y, area.right, y + line_h_}, kHighlight);
            fill(dc, RECT{area.left, y, area.left + 3, y + line_h_}, kAccent);
        } else if (in_statement) {
            fill(dc, RECT{area.left, y, area.right, y + line_h_}, kStmt);
        }
        if (bp_addrs_.count(instruction.addr) != 0) {
            HBRUSH brush = CreateSolidBrush(kRed);
            const HGDIOBJ old_brush = SelectObject(dc, brush);
            const HGDIOBJ old_pen = SelectObject(dc, GetStockObject(NULL_PEN));
            Ellipse(dc, area.left + 12, y + 5, area.left + 20, y + 13);
            SelectObject(dc, old_pen);
            SelectObject(dc, old_brush);
            DeleteObject(brush);
        }
        text_right(dc, area.left + kAsmGutter - 8, y, hex4(instruction.addr),
                   kTextDim);
        std::wstring byte_text;
        for (std::size_t b = 0; b < instruction.bytes.size(); ++b) {
            if (b != 0) {
                byte_text += L' ';
            }
            byte_text += wformat(
                L"%02X", static_cast<unsigned>(instruction.bytes[b]));
        }
        text_left(dc, area.left + kAsmGutter + 8, y, byte_text,
                  is_pc ? kText : kTextDim);

        const int text_x = area.left + kAsmGutter + kAsmBytes + 8;
        const std::size_t split = instruction.text.find(' ');
        const std::string mnemonic =
            split == std::string::npos ? instruction.text
                                       : instruction.text.substr(0, split);
        const std::wstring mnemonic_wide = widen(mnemonic);
        const std::wstring text_wide = widen(instruction.text);
        SIZE mnemonic_size{};
        SIZE text_size{};
        SIZE space_size{};
        GetTextExtentPoint32W(dc, mnemonic_wide.c_str(),
                              static_cast<int>(mnemonic_wide.size()),
                              &mnemonic_size);
        GetTextExtentPoint32W(dc, text_wide.c_str(),
                              static_cast<int>(text_wide.size()),
                              &text_size);
        GetTextExtentPoint32W(dc, L" ", 1, &space_size);
        const RECT mnemonic_rect =
            RECT{text_x, y, text_x + mnemonic_size.cx, y + line_h_};
        RECT operand_rect{};
        if (split != std::string::npos) {
            operand_rect =
                RECT{text_x + mnemonic_size.cx + space_size.cx, y,
                     text_x + text_size.cx, y + line_h_};
        }
        asm_mnemonic_rects_[index] = mnemonic_rect;
        asm_operand_rects_[index] = operand_rect;
        if (hover_asm_kind_ == AsmHoverKind::Mnemonic &&
            hover_asm_index_ == index) {
            fill(dc, mnemonic_rect, kAccentDim);
            frame_rect(dc, mnemonic_rect, kAccent);
        } else if (hover_asm_kind_ == AsmHoverKind::Operand &&
                   hover_asm_index_ == index &&
                   operand_rect.right > operand_rect.left) {
            fill(dc, operand_rect, kStmt);
            frame_rect(dc, operand_rect, kAccent);
        }

        COLORREF color = is_pc ? RGB(255, 255, 255)
                               : (in_statement ? kText : kTextDim);
        text_left(dc, text_x, y, text_wide, color);
    }
    RestoreDC(dc, saved);
}

void App::draw_registers(HDC dc) {
    fill(dc, reg_area_, kPanelAlt);
    RECT separator = RECT{reg_area_.left, reg_area_.top, reg_area_.right,
                          reg_area_.top + 1};
    fill(dc, separator, kBorder);

    SelectObject(dc, bold_font_);
    std::wstring title = L"Registers";
    if (registers_modified_) {
        title += L" *";
    }
    text_left(dc, reg_area_.left + 10, reg_area_.top + 3, title,
              registers_modified_ ? kAmber : kAccent);
    if (editing_reg_ >= 0) {
        text_left(dc, reg_area_.left + 92, reg_area_.top + 3,
                  std::wstring(L"EDIT ") + register_name(editing_reg_) +
                      L"  hex",
                  kAccent);
    } else if (registers_modified_) {
        text_left(dc, reg_area_.left + 92, reg_area_.top + 3, L"modified",
                  kTextDim);
    }

    const wchar_t letters[5] = {L'C', L'Z', L'N', L'V', L'I'};
    const std::uint16_t bits[5] = {Cpu::FlagC, Cpu::FlagZ, Cpu::FlagN,
                                   Cpu::FlagV, Cpu::FlagI};
    const std::uint16_t sr = cpu_.sr();
    for (int i = 0; i < 5; ++i) {
        const bool set = (sr & bits[i]) != 0;
        const bool hovered = hover_flag_ == i;
        fill(dc, flag_rects_[i],
             set ? kGreen : (hovered ? kButtonHover : kButtonOff));
        frame_rect(dc, flag_rects_[i],
                   hovered ? kAccent : (set ? kGreen : kBorder));
        SelectObject(dc, bold_font_);
        RECT label = flag_rects_[i];
        SetBkMode(dc, TRANSPARENT);
        SetTextColor(dc, set ? kBg : kTextDim);
        DrawTextW(dc, &letters[i], 1, &label,
                  DT_CENTER | DT_VCENTER | DT_SINGLELINE | DT_NOPREFIX);
    }
    SelectObject(dc, bold_font_);
    text_right(dc, flag_rects_[0].left - 8, reg_area_.top + 4, L"FLAGS:",
               flags_edited_ ? kAmber : kTextDim);

    for (int i = 0; i < 8; ++i) {
        const bool is_pc = i == 5;
        const bool is_editing = i == editing_reg_;
        const bool hovered = i == hover_reg_;
        const bool edited = (edited_regs_mask_ & (1u << i)) != 0;
        fill(dc, reg_rects_[i], is_editing ? kHighlight
                                           : (is_pc ? kStmt : kPanel));
        frame_rect(dc, reg_rects_[i],
                   is_editing || hovered
                       ? kAccent
                       : (edited ? kAmber
                                 : (is_pc ? kAccent : kBorder)));
        SelectObject(dc, ui_font_);
        text_left(dc, reg_rects_[i].left + 7, reg_rects_[i].top + 2,
                  register_name(i),
                  is_editing || is_pc ? kAccent : kTextDim);

        SelectObject(dc, mono_font_);
        if (is_editing) {
            SIZE digits{};
            GetTextExtentPoint32W(dc, L"0000", 4, &digits);
            const int digit_width = static_cast<int>(digits.cx) / 4;
            const int prefix_x = reg_rects_[i].left + 33;
            text_left(dc, prefix_x, reg_rects_[i].top + 1, L"0x", kTextDim);
            const int buffer_x = prefix_x + 18;
            if (edit_fresh_) {
                RECT selection = RECT{buffer_x - 1, reg_rects_[i].top + 2,
                                      buffer_x + 4 * digit_width + 1,
                                      reg_rects_[i].bottom - 2};
                fill(dc, selection, kAccentDim);
            }
            text_left(dc, buffer_x, reg_rects_[i].top + 1, edit_text_, kText);
            const int caret_x =
                buffer_x + static_cast<int>(edit_text_.size()) * digit_width;
            RECT caret = RECT{caret_x, reg_rects_[i].top + 3, caret_x + 1,
                              reg_rects_[i].bottom - 3};
            fill(dc, caret, kAccent);
        } else {
            text_left(dc, reg_rects_[i].left + 33,
                      reg_rects_[i].top + 1, hex4(register_value(i)), kText);
        }
    }
}

void App::draw_variables(HDC dc, const RECT& r) {
    fill(dc, r, kPanel);
    frame_rect(dc, r, kBorder);
    SelectObject(dc, bold_font_);
    std::wstring title = L"Variables";
    if (variables_modified_) {
        title += L" *";
    }
    text_left(dc, r.left + 8, r.top + 5, title,
              variables_modified_ ? kAmber : kAccent);
    SelectObject(dc, mono_font_);
    int y = r.top + 26;
    const int line_height = line_h_;
    const int limit = r.bottom - 3;
    const int name_x = r.left + 16;
    const int value_x = r.left + 164;
    var_hits_.clear();

    auto value_text = [](bool ok, int size, std::uint16_t value) {
        if (!ok) {
            return std::wstring(L"-");
        }
        if (size > 2) {
            return L"[" + std::to_wstring(size) + L" bytes]";
        }
        std::wstring text =
            size == 1
                ? wformat(L"0x%02X", static_cast<unsigned>(value & 0xFF))
                : hex4(value);
        text += L"  " + std::to_wstring(static_cast<unsigned>(value));
        if (size == 2 && static_cast<std::int16_t>(value) < 0) {
            text += L" (" +
                    std::to_wstring(static_cast<int>(
                        static_cast<std::int16_t>(value))) +
                    L")";
        }
        if (size == 1 && value >= 32 && value < 127) {
            text += L"  '";
            text.push_back(static_cast<wchar_t>(value));
            text += L"'";
        }
        return text;
    };

    auto draw_row = [&](bool local, const std::string& name,
                        std::uint16_t address, int size, bool ok,
                        std::uint16_t value) {
        if (y + line_height > limit) {
            return;
        }
        const int index = static_cast<int>(var_hits_.size());
        const RECT row = RECT{r.left + 8, y, r.right - 8, y + line_height};
        const bool hovered = hover_var_ == index;
        const bool is_editing = editing_var_ == index;
        const bool edited =
            edited_vars_.count(variable_key(local, name)) != 0;
        if (is_editing) {
            fill(dc, row, kHighlight);
            fill(dc, RECT{r.left, y, r.left + 3, y + line_height}, kAccent);
        } else if (hovered) {
            fill(dc, row, kStmt);
            fill(dc, RECT{r.left, y, r.left + 3, y + line_height},
                 kAccentDim);
        } else if (edited) {
            fill(dc, RECT{r.left, y, r.left + 3, y + line_height}, kAmber);
        }

        SelectObject(dc, mono_font_);
        const int saved = SaveDC(dc);
        IntersectClipRect(dc, name_x, y, value_x - 6, y + line_height);
        text_left(dc, name_x, y, widen(name), kText);
        RestoreDC(dc, saved);

        if (is_editing) {
            SIZE digits{};
            GetTextExtentPoint32W(dc, L"0000", 4, &digits);
            const int digit_width = static_cast<int>(digits.cx) / 4;
            text_left(dc, value_x, y, L"0x", kTextDim);
            const int buffer_x = value_x + 18;
            if (edit_fresh_) {
                const RECT selection =
                    RECT{buffer_x - 1, y + 2,
                         buffer_x + 4 * digit_width + 1,
                         y + line_height - 2};
                fill(dc, selection, kAccentDim);
            }
            text_left(dc, buffer_x, y, edit_text_, kText);
            const int caret_x =
                buffer_x + static_cast<int>(edit_text_.size()) * digit_width;
            const RECT caret = RECT{caret_x, y + 3, caret_x + 1,
                                    y + line_height - 3};
            fill(dc, caret, kAccent);
        } else {
            text_left(dc, value_x, y, value_text(ok, size, value),
                      ok ? kText : kTextDim);
        }

        var_hits_.push_back(
            VarHit{row, local, name, address, value, size, ok});
        y += line_height;
    };

    const auto locals = locals_now();
    text_left(dc, r.left + 8, y, L"Locals", kTextDim);
    y += line_height;
    if (locals.empty()) {
        text_left(dc, r.left + 16, y, L"(none)", kTextDim);
        y += line_height;
    } else {
        for (const auto& item : locals) {
            draw_row(true, item.name, item.address, item.size, item.ok,
                     item.value);
        }
    }

    const auto globals = globals_now();
    if (!globals.empty() && y + line_height < limit) {
        y += 4;
        text_left(dc, r.left + 8, y, L"Globals", kTextDim);
        y += line_height;
        for (const auto& item : globals) {
            draw_row(false, item.name, item.address, item.size, item.ok,
                     item.value);
        }
    }
}

void App::draw_stack(HDC dc, const RECT& r) {
    fill(dc, r, kPanel);
    frame_rect(dc, r, kBorder);
    SelectObject(dc, bold_font_);
    text_left(dc, r.left + 8, r.top + 5, L"Call stack", kAccent);
    SelectObject(dc, mono_font_);
    int y = r.top + 26;
    const int line_height = line_h_;
    const int limit = r.bottom - 3;
    const auto frames_now = frames();
    for (std::size_t i = 0; i < frames_now.size(); ++i) {
        if (y + line_height > limit) {
            break;
        }
        const auto& frame = frames_now[i];
        std::wstring label = L"#" + std::to_wstring(i) + L"  " +
                             widen(frame.name);
        if (frame.line > 0) {
            label += L"  line " + std::to_wstring(frame.line);
        }
        text_left(dc, r.left + 10, y, label,
                  i == 0 ? kText : kTextDim);
        y += line_height;
    }
    if (frames_now.empty()) {
        text_left(dc, r.left + 10, y, L"(none)", kTextDim);
    }
}

void App::draw_console(HDC dc, const RECT& r) {
    fill(dc, r, kPanel);
    frame_rect(dc, r, kBorder);
    SelectObject(dc, bold_font_);
    text_left(dc, r.left + 8, r.top + 5, L"Console", kAccent);
    SelectObject(dc, mono_font_);
    const int line_height = line_h_;
    const int limit = r.bottom - 3;
    const auto lines = split_lines(console_);
    if (lines.empty()) {
        text_left(dc, r.left + 10, r.top + 26, L"(no output)", kTextDim);
        return;
    }
    const int capacity =
        std::max(1, static_cast<int>(limit - (r.top + 26)) / line_height);
    const int first = std::max(0, static_cast<int>(lines.size()) - capacity);
    int y = r.top + 26;
    for (int i = first; i < static_cast<int>(lines.size()); ++i) {
        if (y + line_height > limit) {
            break;
        }
        text_left(dc, r.left + 10, y, widen(lines[i]), kGreen);
        y += line_height;
    }
}

