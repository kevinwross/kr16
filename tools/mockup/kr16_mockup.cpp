int App::visible_rows(const RECT& area) const {
    return std::max(1, static_cast<int>(area.bottom - area.top) /
                           std::max(1, line_h_));
}

void App::clamp_scrolls() {
    const int visible_c = visible_rows(layout_.cText);
    const int visible_a = visible_rows(layout_.aText);
    c_scroll_ = std::clamp(c_scroll_, 0,
                           std::max(0, static_cast<int>(source_lines_.size()) -
                                           visible_c));
    asm_scroll_ = std::clamp(
        asm_scroll_, 0,
        std::max(0, static_cast<int>(instrs_.size()) - visible_a));
}

void App::ensure_visible() {
    const int visible_c = visible_rows(layout_.cText);
    const int visible_a = visible_rows(layout_.aText);
    const int line = line_at(cpu_.pc());
    if (line > 0) {
        if (line - 1 < c_scroll_) {
            c_scroll_ = std::max(0, line - 4);
        } else if (line - 1 >= c_scroll_ + visible_c) {
            c_scroll_ = line - visible_c + 3;
        }
    }
    if (!instrs_.empty()) {
        if (asm_pc_index_ < asm_scroll_) {
            asm_scroll_ = std::max(0, asm_pc_index_ - 4);
        } else if (asm_pc_index_ >= asm_scroll_ + visible_a) {
            asm_scroll_ = asm_pc_index_ - visible_a + 3;
        }
    }
    clamp_scrolls();
}

void App::refresh() {
    decode_disassembly();
    layout_buttons();
    ensure_visible();
    hover_var_ = -1;
    var_hits_.clear();
    hover_asm_kind_ = AsmHoverKind::None;
    hover_asm_index_ = -1;
    asm_mnemonic_rects_.clear();
    asm_operand_rects_.clear();
}

void App::after_action() {
    refresh();
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

void App::on_size() {
    compute_layout();
    layout_buttons();
    clamp_scrolls();
    InvalidateRect(g_hwnd, nullptr, FALSE);
}

