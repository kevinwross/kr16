void prepare_embedded_libc() {
    std::error_code error;
    const std::filesystem::path directory =
        std::filesystem::temp_directory_path(error) / L"kr16-mock-libc";
    if (error) {
        return;
    }
    const std::filesystem::path resources = directory / L"resources";
    std::filesystem::create_directories(resources, error);
    if (error) {
        return;
    }
    const std::filesystem::path libc = resources / L"libc.s";
    std::ofstream output(libc, std::ios::binary | std::ios::trunc);
    if (!output.good()) {
        return;
    }
    output << kEmbeddedLibc;
    output.close();
    _putenv_s("KR16_RESOURCE_DIR", directory.string().c_str());
}

void log_line(const std::string& text) {
    wchar_t module[32768];
    const DWORD length =
        GetModuleFileNameW(nullptr, module, static_cast<DWORD>(32768));
    if (length == 0) {
        return;
    }
    const std::filesystem::path path =
        std::filesystem::path(module).parent_path() / L"mock.log";
    std::ofstream out(path, std::ios::app);
    if (out.good()) {
        out << text << '\n';
    }
}

